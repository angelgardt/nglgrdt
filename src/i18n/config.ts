// Языки сайта. Единственное место, где они перечислены.
//
// Не путать две разные настройки:
// - язык сайта по умолчанию — английский, его страницы лежат без префикса (/);
// - язык данных — русский: поле ru в src/data обязательно, en — перевод.

/** Все языки сайта. Русские страницы лежат под /ru/. */
export const locales = ['en', 'ru'] as const

export type Locale = (typeof locales)[number]

/** Язык сайта по умолчанию: его адреса без префикса. */
export const defaultLocale: Locale = 'en'

/** Язык, на котором ведутся данные в src/data. */
export const dataLocale: Locale = 'ru'

/**
 * Что показывать на английском:
 * - 'card' — только визитку на / со ссылкой на русское CV (версия 1);
 * - 'full' — полную английскую версию всех страниц.
 * Переключается здесь, когда переводы готовы (ТЗ, раздел 4).
 */
export const englishMode: 'card' | 'full' = 'card'
